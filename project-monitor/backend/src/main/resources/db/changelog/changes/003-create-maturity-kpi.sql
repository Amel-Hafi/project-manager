CREATE TABLE maturity_kpi (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT NOT NULL UNIQUE,
    industrialization INT,
    code_quality INT,
    testing INT,
    deployment INT,
    obsolescence INT,
    ai_adoption INT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_kpi_application FOREIGN KEY (application_id) REFERENCES application(id)
);
